    hhmm = re.search(r"\b(\d{1,2}:\d{2})\b", msg)
    if not target and not hhmm:
        raise UserError("invalid_value", field="manager_mock_supported_command")
    if target:
        g["target"] = int(target.group(1))
    if hhmm:
        g["time_of_day"] = hhmm.group(1).zfill(5)
    source_names = {"google": r"google|谷歌", "web": r"\bweb\b|网页", "youtube": r"youtube|油管", "tg": r"\btg\b|telegram|电报"}
    sources = [k for k, pattern in source_names.items() if re.search(pattern, msg, re.I)]
    if sources:
        g["sources"] = sources
    if re.search(r"启用|开启|开始|enable|start", msg, re.I):
        g["enabled"] = True
    if re.search(r"停用|关闭|disable", msg, re.I):
        g["enabled"] = False
    return {"goal": g, "explanation": "(mock test) Parsed only explicit target/time/source changes; confirm to save."}


