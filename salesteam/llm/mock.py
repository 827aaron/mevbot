def _ob_extract(ctx):
    facts = []
    for p in ctx.get("pages") or []:
        if str(p.get("url", "")).startswith("input:"):      # 客户自己写的一句话 / 介绍：整段作为公司要点
            txt = (p.get("markdown") or "").strip()
            if txt:
                facts.append({"category": "company", "text": txt[:200], "source_url": p["url"]})
            continue
        for line in re.split(r"[\n.]+", p.get("markdown", "")):
            line = re.sub(r"[#*\-\[\]()]|https?://\S+|/\S+", " ", line).strip()
            if len(line) < 12:
                continue
            cat = next((c for c, rx in _CAT_RULES if re.search(rx, line, re.I)), None)
            if cat:
                facts.append({"category": cat, "text": line[:200], "source_url": p["url"]})
            if len(facts) >= 25:
                break
    return {"facts": facts}


