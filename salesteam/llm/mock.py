    pages = ctx.get("pages") or []
    zh = _zh(ctx)
    country = countries.normalize_country(cand.get("country", ""))
    ctype = (cand.get("customer_type") or "").lower()
    country_ok = country in (icp.get("countries") or [])
    type_ok = any(ctype and (ctype in t.lower() or t.lower() in ctype) for t in icp.get("customer_types") or [])
    text = " ".join([cand.get("company_name", ""), cand.get("description", ""), ctype]).lower()
    excluded = any(k.lower() in text for k in icp.get("exclude_words") or [] if k)
    emails = list(cand.get("emails") or [])
    for p in pages:
        for e in re.findall(r"[\w.+-]+@[\w-]+\.example", p.get("markdown", "")):
            if e not in emails:
                emails.append(e)
    signal = bool(cand.get("buying_signal")) or "looking for new suppliers" in text
    if cand.get("message_type") == "buy_request":
        type_ok = True   # TG 求购消息：发言人类型未知时，按求购信号判断（测试规则）
