def mock_kind(text: str) -> str:
    low = (text or "").lower()
    if re.search(r"sell|promo|cheap|vip|discount|signals|factory price|jual|diskaun|工厂直供|最低价|加入我们", low):
        return "advertisement"
    if any(w in low for w in MOCK_BUY):
        return "buy_request"
    return "chit_chat"


def _tg_classify(ctx):
    _mock_kind = mock_kind
    items = []
    for i, m in enumerate(ctx.get("messages") or []):
        text = m.get("text", "")
        kind = _mock_kind(text)
        qty = re.search(r"(\d[\d,.]*)\s*(units|unit|pcs|biji|台|片|件|pieces)?", text)
        country = next((c for c in ("Malaysia", "Singapore", "Kuala Lumpur", "Johor", "Penang", "Selangor",
                                    "马来西亚", "新加坡", "吉隆坡", "新山", "槟城") if c.lower() in text.lower()), "")
        company = ""
        name = m.get("sender_name") or ""
        if "(" in name and name.endswith(")"):
            company = name[name.index("(") + 1:-1]
        items.append({"idx": i, "message_type": kind if kind != "chit_chat" else "chit_chat",
                      "intent": ("high" if qty else "medium") if kind == "buy_request" else "none",
                      "need": text[:160] if kind == "buy_request" else "", "product": "", "quantity": qty.group(1) if qty else "",
                      "country": countries.infer_country(country)[0] if country else "",
                      "company": company, "reason": "(test mock) keyword rules"})
