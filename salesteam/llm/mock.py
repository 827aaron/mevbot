def _spot_check(ctx):
    """裁判抽查（测试）：分数 ≥ 75 同意；60–75 拿不准；< 60 不同意。"""
    sc = int(ctx.get("score") or 0)
    if sc >= 75:
        return {"agree": True, "confidence": 0.9, "reason": "(test mock) strong evidence"}
    if sc >= 60:
        return {"agree": True, "confidence": 0.6, "reason": "(test mock) not sure"}
    return {"agree": False, "confidence": 0.8, "reason": "(test mock) weak evidence"}


def _manager_goal(ctx):
    """Limited deterministic parser for opt-in mock mode, never real autonomy."""
    from ..errors import UserError
    g = dict(ctx.get("current_goal") or {})
    msg = str(ctx.get("message") or "")
    if not g.get("icp_id"):
        raise UserError("invalid_value", field="manager_mock_set_goal_first")
    if re.search(r"销售|跟进|发信|私信|预算|上限|筛选|sales|follow.?up|email|budget|filter", msg, re.I):
        raise UserError("invalid_value", field="manager_mock_supported_command")
